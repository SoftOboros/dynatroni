#!/usr/bin/env bash
set -euo pipefail

# Configure PostgreSQL memory settings and pg_hba.conf
# Reads from /etc/default/dumbo-secrets (populated by dumbo-fetch-secrets.sh)

SECRETS_FILE=${1:-/etc/default/dumbo-secrets}
CONF_DIR="/etc/postgresql/16/main/conf.d"
PG_HBA="/etc/postgresql/16/main/pg_hba.conf"

echo "[dumbo-configure-pg] Configuring PostgreSQL..."

# Load environment
if [[ -f "$SECRETS_FILE" ]]; then
  source "$SECRETS_FILE"
else
  echo "[dumbo-configure-pg] WARNING: $SECRETS_FILE not found, using defaults"
fi

# Default values (t4g.small / 2GB)
PG_SHARED_BUFFERS=${PG_SHARED_BUFFERS:-256MB}
PG_EFFECTIVE_CACHE_SIZE=${PG_EFFECTIVE_CACHE_SIZE:-768MB}
PG_WORK_MEM=${PG_WORK_MEM:-8MB}
PG_MAINTENANCE_WORK_MEM=${PG_MAINTENANCE_WORK_MEM:-64MB}

# Generate memory configuration file
echo "[dumbo-configure-pg] Writing memory configuration to ${CONF_DIR}/99-memory.conf"
cat > "${CONF_DIR}/99-memory.conf" <<EOF
# Generated by dumbo-configure-pg.sh at $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Memory settings tuned via SSM Parameter Store

# Shared memory (25% of RAM recommended)
shared_buffers = $PG_SHARED_BUFFERS

# Planner memory estimate (50-75% of RAM)
effective_cache_size = $PG_EFFECTIVE_CACHE_SIZE

# Per-query memory
work_mem = $PG_WORK_MEM

# Maintenance operations (VACUUM, CREATE INDEX)
maintenance_work_mem = $PG_MAINTENANCE_WORK_MEM

# Checkpoint settings for gp3 EBS
checkpoint_completion_target = 0.9
wal_buffers = 16MB
min_wal_size = 1GB
max_wal_size = 4GB
EOF

chown postgres:postgres "${CONF_DIR}/99-memory.conf"
chmod 644 "${CONF_DIR}/99-memory.conf"

# Generate pg_hba.conf
# Security group controls network access; pg_hba.conf just authenticates what gets through
# Patroni HA: includes replication access for cluster members in VPC
echo "[dumbo-configure-pg] Writing $PG_HBA"
cat > "$PG_HBA" <<EOF
# PostgreSQL Client Authentication Configuration File
# Generated by dumbo-configure-pg.sh at $(date -u +%Y-%m-%dT%H:%M:%SZ)
#
# Security: Network access is controlled by the security group (DUMBO_CA).
# Only traffic allowed by the SG can reach this instance.
# pg_hba.conf authenticates connections that pass the SG firewall.
#
# Patroni HA: Replication access is granted to the VPC CIDR (10.20.0.0/16)
# for streaming replication between primary and replicas.

# TYPE  DATABASE        USER            ADDRESS                 METHOD

# Local connections (peer auth for postgres user)
local   all             postgres                                peer
local   all             all                                     scram-sha-256

# Replication connections (Patroni HA - allow from VPC CIDR)
local   replication     all                                     peer
host    replication     replicator      10.20.0.0/16            scram-sha-256
host    replication     replicator      127.0.0.1/32            scram-sha-256
host    replication     replicator      ::1/128                 scram-sha-256

# IPv4 host connections (VPC traffic - password auth)
host    all             all             10.20.0.0/16            scram-sha-256

# External connections (SG filters traffic)
host    all             all             0.0.0.0/0               scram-sha-256

# IPv6 host connections
host    all             all             ::0/0                   scram-sha-256
EOF

chown postgres:postgres "$PG_HBA"
chmod 640 "$PG_HBA"

echo "[dumbo-configure-pg] PostgreSQL configuration complete"
echo "[dumbo-configure-pg] Memory: shared_buffers=$PG_SHARED_BUFFERS, effective_cache_size=$PG_EFFECTIVE_CACHE_SIZE"
exit 0
